import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as THREE from "three";
import { FBXLoader } from "three/examples/jsm/loaders/FBXLoader.js";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import { fingerCorrections, repairFingerChannels } from "./lib/companion-fingers.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const sourceFolder = path.join(root, "scripts/characters-src/mixamo-companion-final-character-2026-10-12");
const output = path.resolve(root, process.argv[2] ?? "scripts/characters-src/companion-finger-repair-2026-10-12");
const index = JSON.parse(await readFile(path.join(sourceFolder, "all-six-companions-index.json"), "utf8"));
const buffer = (bytes) => bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
const sourceBytes = await readFile(path.join(root, "scripts/characters-src/mixamo-companion-library-2026-10-12/sources/motions/119340901-texting-while-standing.fbx"));
const source = new FBXLoader().parse(buffer(sourceBytes), "");
source.updateMatrixWorld(true);
const sourceBones = [];
source.traverse((node) => { if (node.isBone) sourceBones.push(node); });
const loader = new GLTFLoader();
loader.register(() => ({ name: "EXT_texture_webp", loadTexture: async () => new THREE.Texture() }));
const manifest = { schemaVersion: 1, defaultAnimation: "Texting While Standing", fingerRetarget: "anatomical-palm-frame-v1", characters: [] };
const report = [];
await mkdir(path.join(output, "runtime"), { recursive: true });
for (const entry of index.characters) {
  const sourcePath = path.resolve(sourceFolder, entry.model);
  const bytes = await readFile(sourcePath);
  if (createHash("sha256").update(bytes).digest("hex") !== entry.sha256) throw new Error(`Canonical source changed: ${entry.id}`);
  const gltf = await loader.parseAsync(buffer(bytes), "");
  gltf.scene.traverse((node) => { if (node.isSkinnedMesh) node.skeleton.pose(); });
  gltf.scene.updateMatrixWorld(true);
  const targetBones = [];
  gltf.scene.traverse((node) => { if (node.isBone) targetBones.push(node); });
  const originalRig = targetBones.some((bone) => bone.name === "hand_l");
  const corrections = originalRig ? fingerCorrections(targetBones, sourceBones) : new Map();
  const repaired = repairFingerChannels(bytes, corrections);
  const model = `runtime/${entry.id}.glb`;
  await writeFile(path.join(output, model), repaired.bytes);
  const sourceManifest = JSON.parse(await readFile(path.resolve(sourceFolder, entry.manifest), "utf8"));
  const character = structuredClone(sourceManifest.characters.find((character) => character.id === entry.id));
  character.fingerRetarget = { method: repaired.channels ? "anatomical-palm-frame-v1" : "unchanged-mixamo-rig", fingerBones: corrections.size, rotationChannels: repaired.channels };
  const sha256 = createHash("sha256").update(repaired.bytes).digest("hex");
  character.model = model; character.sha256 = sha256; character.bytes = repaired.bytes.length;
  character.originalAuthoringBlend = path.relative(output, path.resolve(sourceFolder, entry.authoringBlend));
  delete character.authoringBlend;
  character.validationReport = "repair-report.json";
  manifest.characters.push(character);
  report.push({ id: entry.id, sourceSha256: entry.sha256, sha256, channels: repaired.channels, fingerBones: corrections.size,
    alignmentDegrees: Object.fromEntries([...corrections].map(([name, { alignment }]) => [name, alignment.angleTo(new THREE.Quaternion()) * 180 / Math.PI])) });
  entry.model = model; entry.manifest = "manifest.json"; entry.sha256 = sha256;
  entry.originalAuthoringBlend = path.relative(output, path.resolve(sourceFolder, entry.authoringBlend));
  delete entry.authoringBlend;
  console.log(entry.id, corrections.size, "finger bones;", repaired.channels, "rotation channels repaired");
}
index.defaultAnimation = "Texting While Standing";
index.status = "finger-axis-repaired";
index.blenderPreview = path.relative(output, path.join(sourceFolder, "blender/all-six-companions-preview.blend"));
await writeFile(path.join(output, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
await writeFile(path.join(output, "all-six-companions-index.json"), JSON.stringify(index, null, 2) + "\n");
await writeFile(path.join(output, "repair-report.json"), JSON.stringify(report, null, 2) + "\n");
