import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { beforeEach, afterEach, expect, it, vi } from "vitest";
import type { PhotoState } from "./types";
const command=vi.hoisted(()=>vi.fn(async(..._args:unknown[])=>undefined as unknown));
vi.mock("./runtime",()=>({runPhotoCommand:command,controlsLocked:(state:{busy:boolean;quiet?:boolean})=>state.busy&&!state.quiet,usePhotoWorkspace:Object.assign((selector:(state:{busy:boolean})=>unknown)=>selector({busy:false}),{getState:()=>({busy:false})})}));
import { PatternPresetsPanel, ShapePresetsPanel, ToolPresetsPanel } from "./AdditionalPresets";
let container:HTMLDivElement,root:Root;
const state={width:800,height:600,presets:{patterns:[{name:"Textures",presets:[{id:"pattern-id",name:"Paper",width:16,height:16}]}],pattern:"pattern-id",shapes:[{name:"Symbols",presets:[{name:"Star"}]}],tools:[{name:"Radial",tool:"gradient"},{name:"Pencil",tool:"pencil"}]}} as PhotoState;
beforeEach(()=>{command.mockReset().mockResolvedValue(undefined);container=document.createElement("div");document.body.append(container);root=createRoot(container);});
afterEach(()=>{act(()=>root.unmount());container.remove();});
const button=(name:string)=>[...container.querySelectorAll("button")].find(button=>button.textContent===name||button.getAttribute("aria-label")===name)!;
it("selects a named pattern and creates an editable fill with its placement settings",async()=>{
  act(()=>root.render(<PatternPresetsPanel state={state}/>));
  await act(async()=>button("Paper16 × 16").click());
  expect(command).toHaveBeenCalledWith("pattern.presets.select",{pattern:"pattern-id"});
  await act(async()=>button("New pattern fill").click());
  expect(command).toHaveBeenLastCalledWith("pattern.presets.apply",{pattern:"pattern-id",scale:100,angle:0});
});
it("places vector shape presets with explicit dimensions and current paint color",async()=>{
  act(()=>root.render(<ShapePresetsPanel state={state} foreground="#123456"/>));
  await act(async()=>button("Place shape Star").click());
  expect(command).toHaveBeenCalledWith("shape.presets.place",{preset:"Star",group:"Symbols",rect:[272,172,256,256],keepAspect:true,fill:"#123456"});
});
it("restores host tool options and saves them with the native tool preset",async()=>{
  const choose=vi.fn(),options={toolOptions:{gradientStyle:"radial",gradientReverse:true}};
  command.mockResolvedValue({tool:"gradient",options});
  act(()=>root.render(<ToolPresetsPanel state={state} tool="paint.gradient" options={options} choose={choose}/>));
  expect(container.textContent).not.toContain("Pencil");
  await act(async()=>button("Radialgradient").click());expect(choose).toHaveBeenCalledWith({tool:"gradient",options});
  await act(async()=>container.querySelector("form")!.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true})));
  expect(command).toHaveBeenLastCalledWith("tool.presets.new",{name:"My tool preset",tool:"gradient",options});
});
it("organizes presets in Photoshop's folder groups: right-click to rename or delete, drag onto a group to move, footer for groups",async()=>{
  const patterns=[{name:"Textures",presets:[{id:"pattern-id",name:"Paper",width:16,height:16}]},{name:"Mine",presets:[]}];
  act(()=>root.render(<PatternPresetsPanel state={{...state,presets:{...state.presets!,patterns}}}/>));
  const context=(element:Element)=>act(()=>{element.dispatchEvent(new MouseEvent("contextmenu",{bubbles:true,cancelable:true,clientX:20,clientY:20}));});
  const rows=()=>[...document.querySelectorAll<HTMLButtonElement>("[role=menu] > button")];
  const choose=(label:string)=>act(()=>rows().find(item=>item.textContent===label)!.click());
  const dialog=()=>document.querySelector<HTMLFormElement>("[role=dialog]");
  const submit=()=>act(async()=>{dialog()!.dispatchEvent(new Event("submit",{bubbles:true,cancelable:true}));});
  context(button("Paper16 × 16"));
  expect(rows().map(item=>item.textContent)).toEqual(["Rename Pattern…","Delete Pattern"]);
  choose("Rename Pattern…");
  expect(dialog()?.getAttribute("aria-label")).toBe("Pattern Name");
  act(()=>{const input=dialog()!.querySelector("input")!;Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value")!.set!.call(input,"Kraft");input.dispatchEvent(new Event("input",{bubbles:true}));});
  await submit();
  expect(command).toHaveBeenLastCalledWith("pattern.presets.edit",{action:"rename",group:"Textures",preset:"pattern-id",name:"Kraft"});
  expect(dialog()).toBeNull();
  context(button("Paper16 × 16"));choose("Delete Pattern");
  expect(command).toHaveBeenLastCalledWith("pattern.presets.edit",{action:"delete",group:"Textures",preset:"pattern-id"});
  let hovered:Element|null=null;Object.defineProperty(document,"elementFromPoint",{configurable:true,value:()=>hovered});
  const drag=(over:Element,group:HTMLElement)=>{hovered=over;act(()=>{button("Paper16 × 16").dispatchEvent(new MouseEvent("pointerdown",{bubbles:true,button:0,clientX:0,clientY:0}));window.dispatchEvent(new MouseEvent("pointermove",{clientX:0,clientY:30}));});const shown=group.dataset.drop;act(()=>{window.dispatchEvent(new MouseEvent("pointerup",{clientX:0,clientY:30}));button("Paper16 × 16").click();});return shown;};
  const mine=button("Mine").parentElement!,textures=button("Textures").parentElement!;
  expect(drag(textures,textures)).toBeUndefined();
  expect(command).toHaveBeenCalledTimes(2);
  expect(drag(button("Mine"),mine)).toBe("into");expect(mine.dataset.drop).toBeUndefined();
  expect(command).toHaveBeenLastCalledWith("pattern.presets.edit",{action:"move",group:"Textures",preset:"pattern-id",to:"Mine"});
  Reflect.deleteProperty(document,"elementFromPoint");
  context(button("Textures"));
  expect(rows().map(item=>item.textContent)).toEqual(["New Group…","Rename Group…","Delete Group"]);
  choose("Delete Group");
  expect(dialog()?.textContent).toContain("Delete the group “Textures” and all of its presets?");
  expect(command).toHaveBeenCalledTimes(3);
  await submit();
  expect(command).toHaveBeenLastCalledWith("pattern.presets.edit",{action:"deleteGroup",group:"Textures"});
  await act(async()=>button("Create new group").click());
  expect(dialog()?.getAttribute("aria-label")).toBe("Group Name");
  await submit();
  expect(command).toHaveBeenLastCalledWith("pattern.presets.edit",{action:"newGroup",name:"Group 3"});
  await act(async()=>button("Textures").click());
  expect(button("Textures").getAttribute("aria-expanded")).toBe("false");
  expect(container.textContent).not.toContain("Paper");
});
